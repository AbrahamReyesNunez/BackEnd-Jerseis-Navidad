-- ---------------------------------------------------------------------
-- Usuarios
-- ---------------------------------------------------------------------
CREATE TABLE usuarios (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email                   VARCHAR(254) NOT NULL UNIQUE,
    -- Email "limpio" (minúsculas, sin +alias, sin puntos en Gmail) para evitar cuentas duplicadas
    email_normalizado       VARCHAR(254) NOT NULL UNIQUE,
    nombre                  VARCHAR(60)  NOT NULL,
    -- Nunca se guarda la contraseña, solo su hash bcrypt
    password_hash           VARCHAR(100) NOT NULL,
    rol                     VARCHAR(20)  NOT NULL DEFAULT 'USUARIO'
                            CHECK (rol IN ('USUARIO', 'PROFESOR', 'ADMIN')),
    verificado              BOOLEAN      NOT NULL DEFAULT FALSE,
    activo                  BOOLEAN      NOT NULL DEFAULT TRUE,
    fecha_registro          TIMESTAMPTZ  NOT NULL DEFAULT now(),
    ip_registro_hash        VARCHAR(64),
    -- Prueba del consentimiento (protección de datos)
    privacidad_aceptada_en  TIMESTAMPTZ  NOT NULL,
    privacidad_version      VARCHAR(20)  NOT NULL,
    consentimiento_en       TIMESTAMPTZ  NOT NULL,
    mayor_14_confirmado     BOOLEAN      NOT NULL
);

-- ---------------------------------------------------------------------
-- Tokens de un solo uso (verificación de email; en el futuro, recuperar contraseña)
-- ---------------------------------------------------------------------
CREATE TABLE tokens_verificacion (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id  BIGINT       NOT NULL REFERENCES usuarios (id) ON DELETE CASCADE,
    token       VARCHAR(64)  NOT NULL UNIQUE,
    tipo        VARCHAR(30)  NOT NULL CHECK (tipo IN ('VERIFICACION_EMAIL')),
    expira      TIMESTAMPTZ  NOT NULL,
    usado       BOOLEAN      NOT NULL DEFAULT FALSE
);

-- ---------------------------------------------------------------------
-- Jerseys
-- ---------------------------------------------------------------------
CREATE TABLE jerseys (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id          BIGINT       NOT NULL REFERENCES usuarios (id),
    -- Nombre del archivo en el FTP (un UUID, nunca el nombre original)
    imagen_nombre       VARCHAR(100) NOT NULL UNIQUE,
    estado              VARCHAR(20)  NOT NULL DEFAULT 'APROBADO'
                        CHECK (estado IN ('APROBADO', 'ELIMINADO')),
    motivo_eliminacion  VARCHAR(500),
    eliminado_por       BIGINT       REFERENCES usuarios (id),
    fecha_subida        TIMESTAMPTZ  NOT NULL DEFAULT now(),
    fecha_eliminacion   TIMESTAMPTZ
);

-- Un único jersey ACTIVO por usuario. Los eliminados no cuentan, así
-- quien tiene uno eliminado puede subir otro. (Índice único "parcial":
-- solo aplica a las filas que cumplen el WHERE. MySQL no tiene esto.)
CREATE UNIQUE INDEX un_jersey_activo ON jerseys (usuario_id) WHERE estado <> 'ELIMINADO';
CREATE INDEX idx_jerseys_estado ON jerseys (estado);

-- ---------------------------------------------------------------------
-- Votos (sistema "tipo Eurovisión": cada usuario reparte 6,5,4,3,2,1)
-- ---------------------------------------------------------------------
CREATE TABLE votos (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id   BIGINT       NOT NULL REFERENCES usuarios (id),
    jersey_id    BIGINT       NOT NULL REFERENCES jerseys (id),
    puntos       INTEGER      NOT NULL CHECK (puntos BETWEEN 1 AND 6),
    fecha        TIMESTAMPTZ  NOT NULL DEFAULT now(),
    ip_hash      VARCHAR(64),
    user_agent   VARCHAR(300),
    anulado      BOOLEAN      NOT NULL DEFAULT FALSE,
    anulado_por  BIGINT       REFERENCES usuarios (id),
    -- Un usuario no puede votar dos veces el mismo jersey...
    CONSTRAINT un_voto_jersey UNIQUE (usuario_id, jersey_id),
    -- ...ni usar dos veces la misma puntuación
    CONSTRAINT un_voto_puntos UNIQUE (usuario_id, puntos)
);
CREATE INDEX idx_votos_jersey ON votos (jersey_id);

-- ---------------------------------------------------------------------
-- Configuración del concurso: UNA sola fila (id = 1) con las fechas de las fases
-- ---------------------------------------------------------------------
CREATE TABLE configuracion (
    id               INTEGER PRIMARY KEY CHECK (id = 1),
    inicio_subida    TIMESTAMPTZ,
    fin_subida       TIMESTAMPTZ,
    inicio_votacion  TIMESTAMPTZ,
    fin_votacion     TIMESTAMPTZ
);
